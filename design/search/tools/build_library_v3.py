"""Writes exercise-library.json v3 and LiftCore/SearchRules.swift from the search CSVs.

v3 adds per exercise: aliases (from aliases.csv only, replacing the library's),
popularity (1-5), popularityRank (or null), position (attribute words) and
duplicateOf (hidden unless logged). Run from anywhere; paths are repo-relative.
The position/duplicate columns come from design/animations/inventory.csv when it
exists (it's untracked); otherwise the values already in the JSON are kept."""
import csv, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); SEARCH = os.path.dirname(HERE)
ROOT = os.path.dirname(os.path.dirname(SEARCH))
LIB = os.path.join(ROOT, 'Packages/LiftKit/Sources/LiftCore/Resources/exercise-library.json')
INV = os.path.join(ROOT, 'design/animations/inventory.csv')
SWIFT = os.path.join(ROOT, 'Packages/LiftKit/Sources/LiftCore/SearchRules.swift')
sys.path.insert(0, HERE)

D = json.load(open(LIB)); L = D['exercises']
al = {r['exercise_id']: [a for a in r['aliases'].split('|') if a] for r in csv.DictReader(open(os.path.join(SEARCH, 'aliases.csv')))}
pop = {r['exercise_id']: (int(r['popularity']), int(r['rank']) if r['rank'] else None) for r in csv.DictReader(open(os.path.join(SEARCH, 'popularity.csv')))}
inv = {r['id']: r for r in csv.DictReader(open(INV))} if os.path.exists(INV) else None
for e in L:
    e['aliases'] = al.get(e['id'], [])
    e['popularity'], e['popularityRank'] = pop[e['id']]
    if inv is not None:
        r = inv[e['id']]
        e['position'] = r['position'] or ''
        e['duplicateOf'] = r['duplicate_of'] or None
# Common wins a duplicate pair: triceps-pushdown stays, tricep-pushdowns hides (§10.2).
byid = {e['id']: e for e in L}
byid['triceps-pushdown']['duplicateOf'] = None
byid['tricep-pushdowns']['duplicateOf'] = 'triceps-pushdown'
D['version'] = 3
with open(LIB, 'w') as f:
    json.dump(D, f, ensure_ascii=False, separators=(',', ':'))
print('library v3:', len(L), 'exercises,', sum(len(e['aliases']) for e in L), 'aliases,',
      sum(1 for e in L if e.get('duplicateOf')), 'hidden duplicates')

# Swift tables (never parsed per keystroke).
import search_ref as s
R = s.R
def lit(x): return json.dumps(x, ensure_ascii=False)
def dmap(d): return '[' + ', '.join('%s: %s' % (lit(k), lit(v)) for k, v in d.items()) + ']' if d else '[:]'
pairs = [(a.split(), b.split()) for a, b in R['pair'].items()]
muscles = {k: sorted(v) for k, v in s.MUSCLE.items()}
out = f'''// Generated by design/search/tools/build_library_v3.py from expansions.csv. Do not edit.
// swiftlint:disable all

enum SearchRules {{
    static let typo: [String: String] = {dmap(R['typo'])}
    static let token: [String: String] = {dmap(R['token'])}
    static let phrase: [String: String] = {dmap(R['phrase'])}
    /// Two-token rewrites, applied in file order, left to right.
    static let pairs: [([String], [String])] = [{', '.join('(%s, %s)' % (lit(a), lit(b)) for a, b in pairs)}]
    static let generic: Set<String> = [{', '.join(lit(x) for x in sorted(R['generic']))}]
    static let noStem: Set<String> = [{', '.join(lit(x) for x in sorted(R['keep']))}]
    /// Single muscle or body-part words (tier 5) → primary muscle raw values.
    static let muscles: [String: Set<String>] = [{', '.join('%s: [%s]' % (lit(k), ', '.join(lit(m) for m in v)) for k, v in muscles.items())}]
}}
'''
open(SWIFT, 'w').write(out)
print('wrote', os.path.relpath(SWIFT, ROOT))
