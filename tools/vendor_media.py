#!/usr/bin/env python3
"""Vendor the cleared CC0 exercise media into App/Resources/ExerciseMedia and
write THIRD_PARTY_MEDIA.md (one line per file: source URL, licence, size, sha256).

Only two sources are allowed (both CC0 1.0):
  - open-exercise-illustrations (hitmanrepo) stills
  - workout-free-videos v2.0.0 (namnq) MP4s
free-exercise-db photos are never used. Run once; the app never hot-links.
"""
import json, hashlib, pathlib, sys, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "research/exercises.json"
DEST = ROOT / "App/Resources/ExerciseMedia"
DOC = ROOT / "THIRD_PARTY_MEDIA.md"
OEI = ("open-exercise-illustrations", "https://github.com/hitmanrepo/open-exercise-illustrations",
       "CC0 1.0", "https://github.com/hitmanrepo/open-exercise-illustrations/blob/main/LICENSE")
WFV = ("workout-free-videos v2.0.0", "https://github.com/namnq/workout-free-videos",
       "CC0 1.0", "https://github.com/namnq/workout-free-videos/blob/main/LICENSE")

def plan():
    for e in json.loads(SRC.read_text()):
        r, i = e.get("mediaRef"), e["id"]
        if not r: continue
        if "hitmanrepo/open-exercise-illustrations" in r and r.endswith("/start.webp"):
            yield i, OEI, r, f"stills/{i}-start.webp"
            yield i, OEI, r.replace("/start.webp", "/end.webp"), f"stills/{i}-end.webp"
        elif "hitmanrepo/open-exercise-illustrations" in r and r.endswith("/hold.webp"):
            yield i, OEI, r, f"stills/{i}-hold.webp"
        elif "namnq/workout-free-videos@v2.0.0" in r and r.endswith(".mp4"):
            yield i, WFV, r, f"video/{i}.mp4"
        else:
            sys.exit(f"{i}: mediaRef not from a cleared source: {r}")

def main():
    rows, total = [], {"stills": 0, "video": 0}
    for i, src, url, rel in plan():
        p = DEST / rel
        if not p.exists():
            p.parent.mkdir(parents=True, exist_ok=True)
            with urllib.request.urlopen(url) as resp: p.write_bytes(resp.read())
        data = p.read_bytes()
        total[rel.split("/")[0]] += len(data)
        rows.append((rel, i, src, url, len(data), hashlib.sha256(data).hexdigest()[:16]))
    mb = lambda b: f"{b / 1e6:.1f} MB"
    out = ["# Third-party media", "",
           "Every media file bundled in the app, with its source and licence. Generated by `tools/vendor_media.py`; do not edit by hand.", "",
           "Exercise text data comes from free-exercise-db (Unlicense, no attribution required), open-exercise-illustrations and workout-free-videos metadata (CC0), and Lift's own entries. **No free-exercise-db photographs are used.**", "",
           "| Source | Licence | Files | Size |", "|---|---|---:|---:|",
           f"| [{OEI[0]}]({OEI[1]}) | [{OEI[2]}]({OEI[3]}) | {sum(1 for r in rows if r[2] is OEI)} WebP stills | {mb(total['stills'])} |",
           f"| [{WFV[0]}]({WFV[1]}) | [{WFV[2]}]({WFV[3]}) | {sum(1 for r in rows if r[2] is WFV)} MP4 videos | {mb(total['video'])} |",
           f"| **Total** | | {len(rows)} | **{mb(sum(total.values()))}** |", "",
           "CC0 waives copyright; it does not clear publicity rights of people shown in the workout-free-videos clips. Open-exercise-illustrations are AI mannequin drawings.", "",
           "## Files", "", "| File (under App/Resources/ExerciseMedia) | Exercise id | Source | Original URL | Licence | Bytes | sha256 (16) |", "|---|---|---|---|---|---:|---|"]
    out += [f"| `{rel}` | `{i}` | {src[0]} | {url} | {src[2]} | {n} | `{h}` |" for rel, i, src, url, n, h in rows]
    DOC.write_text("\n".join(out) + "\n")
    print(f"{len(rows)} files; stills {mb(total['stills'])}, video {mb(total['video'])}, total {mb(sum(total.values()))}")

if __name__ == "__main__":
    main()
